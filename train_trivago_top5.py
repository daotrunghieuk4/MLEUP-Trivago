"""Train MLEUP variants with selected Trivago metadata fields.

The original modes use full-catalog cross-entropy. The experimental
event_graph_candidate mode instead trains and evaluates over each clickout's
impression list so its candidate-conditioned event readout is supervised
directly. This is not an official hidden-test submission.
Report validation NDCG@5/Recall@5 and train/validation losses each epoch.
Stop on validation NDCG stagnation OR sustained CE loss divergence, patience 3.
Both objectives include the metadata contrastive loss; best selection is NDCG.
"""

