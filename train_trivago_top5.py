class TimeBudgetExceeded(Exception):
    pass


def load_pickle(path: Path):
    with path.open("rb") as source:
        return pickle.load(source)  # Only use files generated by this project.


def fingerprint_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def atomic_save(payload: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    torch.save(payload, temporary)
    os.replace(temporary, path)


def write_status(output_dir: Path, **status) -> None:
    (output_dir / "run_status.json").write_text(
        json.dumps(status, indent=2), encoding="utf-8"
    )


def backup_training_policy(output_dir: Path) -> Path:
    """Preserve the old run before migrating its training policy in-place."""
    destination = output_dir / 'training_policy_backups' / str(time.time_ns())
    destination.mkdir(parents=True, exist_ok=False)
    for name in ('result_latest.pth', 'result_best.pth', 'run_status.json', 'metric_history.json'):
        source = output_dir / name
        if source.is_file():
            shutil.copy2(source, destination / name)
    return destination


def make_data(prepared_dir: Path, split: str, config: dict, options):
    data = load_pickle(prepared_dir / f"{split}.txt")
    if not isinstance(data, list) or len(data) not in (2, 3, 4):
        raise ValueError(f"Invalid {split} payload; expected [items, targets] or v3 action payload")
    action_sequences = None
    event_sequences = None
    candidate_lists = None
    candidate_price_records = None
    price_scaler = None
    if options.action_mode in ("item_event", "event_graph_candidate"):
        expected_parts = 3
        if len(data) != expected_parts:
            raise ValueError(f"{options.action_mode} requires a {expected_parts}-part {split}.txt payload")
        action_sequences = data[2]
    if options.action_mode == "event_graph_candidate":
        candidate_lists = load_candidates(prepared_dir, split)
    price_mode = getattr(options, "price_mode", "off")
    if price_mode != "off":
        if options.action_mode != "event_graph_candidate":
            raise ValueError("Price ranking is supported only with event_graph_candidate")
        price_config = config.get("price_features", {})
        if (price_config.get("schema") != PRICE_ARTIFACT_SCHEMA
                or price_config.get("price_schema") != PRICE_FEATURE_SCHEMA
                or price_config.get("feature_order") != list(PRICE_FEATURE_ORDER)):
            raise ValueError("Prepared data lacks the compatible price feature schema; rebuild it")
        price_scaler = price_config.get("scaler")
        if not isinstance(price_scaler, dict) or price_scaler.get("count", 0) < 1:
            raise ValueError("Price mode requires at least one valid positive train price")
        candidate_price_records = load_pickle(
            prepared_dir / f"{split}_candidate_prices.pkl"
        )
        if candidate_price_records.get("schema") != PRICE_FEATURE_SCHEMA:
            raise ValueError("Candidate price record schema mismatch")
        if candidate_price_records.get("source_train_sha256") != config.get("source_train_sha256"):
            raise ValueError("Candidate price records reference a different raw train.csv")
        if candidate_price_records.get("query_manifest_sha256") != config.get(
                "query_manifest_sha256", {}).get(split):
            raise ValueError("Candidate price query manifest does not align with prepared examples")
    if options.action_mode == 'all_event':
        expected_parts = 4
        if len(data) != expected_parts:
            raise ValueError(f'all_event requires {expected_parts} payload parts; rebuild preprocessing')
        event_sequences = data[3]
        if any(token >= options.num_event_tokens for seq in event_sequences for token in seq):
            raise ValueError('Event token outside fitted vocabulary')
    groups = load_pickle(prepared_dir / (
        f"{split}_groups_{config['m']}_{config['frequency']}.txt"
    ))
    dataset = Data(data, groups, options.sample_order, options.si_dc,
                   lazy_graphs=True, action_sequences=action_sequences,
                   event_sequences=event_sequences,
                   candidate_lists=candidate_lists,
                   candidate_price_records=candidate_price_records,
                   price_scaler=price_scaler)
    del data, groups
    return dataset


def load_candidates(prepared_dir: Path, split: str):
    return load_pickle(prepared_dir / f"{split}_candidates.txt")


def batch_at(dataset, indices: list[int]):
    return collate_fn([dataset[index] for index in indices])


def check_time(started: float, max_hours: float) -> None:
    if max_hours and time.monotonic() - started >= max_hours * 3600:
        raise TimeBudgetExceeded


@torch.no_grad()
def evaluate(model: MLEUP, dataset: Data, candidates: list, batch_size: int,
             started: float = 0, max_hours: float = 0, include_loss: bool = False) -> dict:
    if len(candidates) != len(dataset):
        raise ValueError("Candidate lists must align with the evaluation examples")
    model.eval()
    count = 0
    recall5 = 0.0
    ndcg5 = 0.0
    ce_sum = metadata_sum = 0.0
    for offset in range(0, len(dataset), batch_size):
        indices = list(range(offset, min(offset + batch_size, len(dataset))))
        targets, scores, metadata_loss = forward(model, batch_at(dataset, indices))
        # Transfer only impression scores, once per batch. Ranking scalar-by-
        # scalar on CUDA would synchronize the GPU three times per example.
        if model.action_mode == "event_graph_candidate":
            batch_candidates = [dataset.candidate_lists[index] for index in indices]
        else:
            batch_candidates = [normalize_candidate_list(candidates[index]) for index in indices]
        if any(not item_ids for item_ids in batch_candidates):
            raise ValueError("Evaluation candidates cannot be empty")
        width = max(map(len, batch_candidates))
        positions = torch.as_tensor(
            [item_ids + [0] * (width - len(item_ids)) for item_ids in batch_candidates],
            device=scores.device, dtype=torch.long,
        )
        if model.action_mode == "event_graph_candidate":
            candidate_scores = scores.cpu()
            target_ids = dataset.targets[indices].tolist()
        else:
            candidate_scores = scores.gather(1, positions).cpu()
            target_ids = targets.cpu().tolist()
        for row, source_index in enumerate(indices):
            item_ids = batch_candidates[row]
            target_id = int(target_ids[row])
            target_position = item_ids.index(target_id)
            values = candidate_scores[row, :len(item_ids)]
            if not torch.isfinite(values).all():
                raise FloatingPointError(
                    f"Non-finite impression scores for evaluation example {source_index}; "
                    "metrics and best checkpoint were not updated"
                )
            target_score = values[target_position]
            before = torch.arange(len(item_ids)).lt(target_position)
            rank = 1 + (values > target_score).sum().item() + (
                values.eq(target_score) & before
            ).sum().item()
            count += 1
            # One relevant target per clickout: Recall@5 equals Hit@5.
            recall5 += int(rank <= 5)
            ndcg5 += 1.0 / np.log2(rank + 1) if rank <= 5 else 0.0
        if include_loss:
            ce = torch.nn.functional.cross_entropy(scores, targets)
            total = ce + metadata_loss
            if not torch.isfinite(total):
                raise FloatingPointError('Non-finite validation loss; metrics were not committed')
            ce_sum += float(ce) * len(indices)
            metadata_sum += float(metadata_loss) * len(indices)
        if offset % (batch_size * 500) == 0:
            print(f"  eval: {offset:,}/{len(dataset):,}", flush=True)
        if started:
            check_time(started, max_hours)
    if not count:
        raise ValueError("Cannot evaluate an empty split")
    result = {"ndcg_at_5": ndcg5 / count,
              "recall_at_5": recall5 / count,
              "examples": count}
    if include_loss:
        result.update(ce_loss=ce_sum / count, metadata_loss=metadata_sum / count,
                      total_loss=(ce_sum + metadata_sum) / count)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepared-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--emb-size", type=int, default=16)
    parser.add_argument("--num-heads", type=int, default=4)
    parser.add_argument("--sample-order", type=int, default=3)
    parser.add_argument("--si-dc", type=float, default=2.0)
    parser.add_argument("--beta", type=float, default=0.3)
    parser.add_argument("--alpha", type=float, default=0.2)
    parser.add_argument("--lr", type=float, default=0.001)
    parser.add_argument("--lr-factor", type=float, default=0.5)
    parser.add_argument("--lr-patience", type=int, default=1,
                        help="PyTorch plateau patience; 1 reduces LR after 2 bad validation epochs")
    parser.add_argument("--min-lr", type=float, default=1e-5)
    parser.add_argument("--min-delta", type=float, default=1e-4,
                        help="Absolute NDCG gain required to reset the improvement anchor")
    parser.add_argument("--metadata-projection", choices=("concat", "fieldwise"),
                        default="concat")
    parser.add_argument("--action-mode", choices=("none", "item_event", "all_event",
                                                      "event_graph_candidate"), default="none")
    parser.add_argument("--price-mode", choices=("off", "relative_mlp_v1"),
                        default="off")
    parser.add_argument("--checkpoint-every", type=int, default=1000)
    parser.add_argument("--max-hours", type=float, default=8.5)
    parser.add_argument("--patience", type=int, default=3,
                        help="Completed epochs without validation NDCG@5 exceeding anchor + min-delta")
    parser.add_argument("--loss-patience", type=int, default=3,
                        help="Consecutive train-CE-down / validation-CE-up epoch transitions")
    parser.add_argument("--loss-min-delta", type=float, default=0.001,
                        help="Minimum relative change in BOTH CE losses to count as divergence (0.001 = 0.1%%)")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--eval-only", choices=("val", "test"))
    parser.add_argument("--max-batches", type=int, default=0,
                        help="Smoke test only; 0 means full split")
    args = parser.parse_args()
    if min(args.epochs, args.batch_size, args.emb_size, args.num_heads,
           args.sample_order, args.checkpoint_every, args.patience, args.loss_patience) < 1:
        parser.error("Epoch, batch, embedding, heads, sample-order, checkpoint interval and patience must be >0")
    if args.emb_size % args.num_heads:
        parser.error("emb-size must be divisible by num-heads")
    if args.beta <= 0:
        parser.error("beta must be > 0 so the metadata contrastive branch remains active")
    if (not all(np.isfinite(v) for v in (args.lr, args.min_lr, args.lr_factor,
                                         args.min_delta, args.loss_min_delta))
            or not 0 < args.min_lr <= args.lr or not 0 < args.lr_factor < 1
            or args.min_delta < 0 or args.loss_min_delta < 0 or args.lr_patience < 0):
        parser.error('Require finite values: 0 < min-lr <= lr, 0 < lr-factor < 1, min-delta/loss-min-delta >= 0, lr-patience >= 0')
    training_policy = checkpoint_training_policy(args)
    config = load_pickle(args.prepared_dir / "config.pkl")
    if config.get("metadata_mode") != "train_filter_top_k":
        raise ValueError("Prepared folder is not the train-filter-selected metadata variant")
    if config.get("group_pair_counts", {}).get("train", {}).get("real_pairs", 0) == 0:
        raise ValueError("No real train positive/negative session pairs; cannot train contrastive metadata")
    if "artifact_sha256" not in config:
        raise ValueError("Prepared data predates artifact fingerprinting; rebuild it")
    token_actions = None
    if args.action_mode in ("item_event", "event_graph_candidate"):
        expected_converter = 'top5_metadata_v3_item_event_actions'
        expected_schema = 3
        expected_action_config = {
            "converter_version": expected_converter,
            "data_schema_version": expected_schema,
            "action_schema_version": ACTION_SCHEMA_VERSION,
            "action_to_id": ACTION_TO_ID,
            "num_actions": NUM_ACTIONS,
            "action_input_scope": ACTION_INPUT_SCOPE,
            "action_history_policy": ACTION_HISTORY_POLICY,
        }
        mismatches = [key for key, value in expected_action_config.items()
                      if config.get(key) != value]
        if mismatches:
            raise ValueError(
                "Prepared action schema mismatch: " + ", ".join(mismatches)
                + ". Re-run preprocessing into the new action-v1 prepared directory."
            )
        schema_payload = {
            "action_to_id": ACTION_TO_ID,
            "pad_action_id": config.get("pad_action_id"),
            "unk_action_id": config.get("unk_action_id"),
            "num_actions": NUM_ACTIONS,
            "action_input_scope": ACTION_INPUT_SCOPE,
            "action_history_policy": ACTION_HISTORY_POLICY,
            "action_schema_version": ACTION_SCHEMA_VERSION,
        }
        canonical = json.dumps(schema_payload, ensure_ascii=False, sort_keys=True,
                               separators=(",", ":")).encode("utf-8")
        expected_action_hash = hashlib.sha256(canonical).hexdigest()
        if config.get("action_schema_sha256") != expected_action_hash:
            raise ValueError("Prepared action schema fingerprint mismatch")
        if config.get("pad_action_id") != 0 or config.get("unk_action_id") != 11:
            raise ValueError("Prepared action PAD/UNK IDs do not match the shared mapping")
    if args.action_mode == 'all_event':
        expected_converter = 'top5_metadata_v4_all_event_pairs'
        expected_data_schema = 4
        if (config.get('converter_version') != expected_converter
                or config.get('data_schema_version') != expected_data_schema):
            raise ValueError(f'all_event needs schema {expected_data_schema}; re-run preparation')
        schema_payload = all_event_schema(config.get('num_event_tokens'), config.get('max_session_events'))
        if any(config.get(k) != v for k, v in schema_payload.items()):
            raise ValueError('Prepared all-event schema mismatch')
        canonical = json.dumps(schema_payload, ensure_ascii=False, sort_keys=True,
                               separators=(',', ':')).encode('utf-8')
        if hashlib.sha256(canonical).hexdigest() != config.get('action_schema_sha256'):
            raise ValueError('Prepared all-event schema fingerprint mismatch')
        if 'event_vocabulary.pkl' not in config['artifact_sha256']:
            raise ValueError('Missing fitted event vocabulary fingerprint')
        vocab = load_pickle(args.prepared_dir / 'event_vocabulary.pkl')
        if (config['num_event_tokens'] != len(vocab) + 11
                or set(vocab.values()) != set(range(11, len(vocab) + 11))):
            raise ValueError('Event vocabulary IDs must be contiguous after per-action unknown IDs')
        token_actions = list(range(11)) + [0] * len(vocab)
        for (action_id, reference), token in vocab.items():
            if action_id not in ACTION_TO_ID.values() or not isinstance(reference, str):
                raise ValueError('Invalid event vocabulary key')
            token_actions[token] = action_id
        del vocab
    for name, expected in config["artifact_sha256"].items():
        actual = fingerprint_file(args.prepared_dir / name)
        if actual != expected:
            raise ValueError(f"Prepared artifact changed: {name}")
    signature = prepared_data_signature(config)
    args.num_actions = NUM_ACTIONS if args.action_mode in ("item_event", "event_graph_candidate") else 0
    args.action_encoder = ACTION_ENCODER if args.action_mode == "item_event" else "none"
    args.action_fusion = ACTION_FUSION if args.action_mode == "item_event" else "none"
    if args.action_mode == "event_graph_candidate":
        args.action_encoder = EVENT_GRAPH_ENCODER
        args.action_fusion = EVENT_GRAPH_FUSION
    args.num_event_tokens = 0
    if args.action_mode == 'all_event':
        args.num_actions = NUM_ACTIONS
        args.num_event_tokens = config['num_event_tokens']
        args.action_encoder = ALL_EVENT_ENCODER
        args.action_fusion = ALL_EVENT_FUSION
    if args.price_mode != 'off' and args.action_mode != 'event_graph_candidate':
        parser.error("--price-mode relative_mlp_v1 requires --action-mode event_graph_candidate")
    model_arguments = checkpoint_model_arguments(args)
    options = SimpleNamespace(
        m=config["m"], emb_size=args.emb_size, batch_size=args.batch_size,
        sample_order=args.sample_order, num_heads=args.num_heads,
        beta=args.beta, alpha=args.alpha, si_dc=args.si_dc,
        metadata_projection=args.metadata_projection,
        action_mode=args.action_mode, num_actions=args.num_actions,
        action_encoder=args.action_encoder, action_fusion=args.action_fusion,
        price_mode=args.price_mode,
        num_event_tokens=args.num_event_tokens,
        event_token_action_ids=token_actions,
        valid_groups_only=True,
    )
    torch.manual_seed(config["seed"])
    np.random.seed(config["seed"])
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(config["seed"])
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    adjacency_fi = load_pickle(args.prepared_dir / "adjacency_fi.txt")
    adjacency_if = load_pickle(args.prepared_dir / "adjacency_if.txt")
    if adjacency_if.shape != (len(config["field_names"]), config["n_node"]):
        raise ValueError("adjacency_if shape does not match config")
    model = MLEUP(options, config["n_node"], config["all_feature"],
                  adjacency_fi, adjacency_if).to(device)
    # Evaluation does not need optimizer state, scheduler or a training loss.
    optimizer = scheduler = loss_function = None
    if not args.eval_only:
        optimizer = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=1e-4)
        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            optimizer, mode='max', factor=args.lr_factor, patience=args.lr_patience,
            threshold=args.min_delta, threshold_mode='abs', cooldown=0, min_lr=args.min_lr)
        loss_function = torch.nn.CrossEntropyLoss()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    latest_path = args.output_dir / "result_latest.pth"
    best_path = args.output_dir / "result_best.pth"
    epoch, next_offset, global_step, best_ndcg = 0, 0, 0, -1.0
    best_epoch, best_offset = None, 0
    metric_history = []
    needs_metric_baseline = False
    training_finished = False
    migrated_policy = False
    early_stopping = new_early_stopping(args.patience, args.loss_patience,
                                        args.min_delta, args.loss_min_delta)
    train_epoch_totals = dict(ce_sum=0.0, metadata_sum=0.0, examples=0)
    if args.eval_only == 'test':
        status_path = args.output_dir / 'run_status.json'
        status = json.loads(status_path.read_text(encoding='utf-8')) if status_path.is_file() else {}
        if status.get('status') not in ('COMPLETE', 'EARLY_STOPPED', 'EVALUATED'):
            raise ValueError('Test metrics are final-only; finish training first')
        if not best_path.is_file():
            raise ValueError('No best NDCG@5 checkpoint available')
    if args.resume or args.eval_only:
        path = best_path if args.eval_only and best_path.is_file() else latest_path
        # Keep the serialized payload off the GPU. load_state_dict copies model
        # weights; Adam moves only its required state to the parameter device.
        checkpoint = torch.load(path, map_location="cpu", weights_only=False)
        validate_checkpoint(checkpoint, signature, model_arguments)
        saved_policy = checkpoint.get('training_policy')
        saved_stopping = checkpoint.get('early_stopping', {})
        if not args.eval_only:
            if saved_policy is not None and saved_policy != training_policy:
                raise ValueError('Resume training policy differs (NDCG/loss thresholds, patience or LR schedule); keep checkpoint settings or use a fresh output directory')
            if saved_policy is not None and saved_stopping.get('version') != EARLY_STOPPING_VERSION:
                raise ValueError('Checkpoint stopping state is missing or incompatible with its training policy')
            if saved_policy is None and saved_stopping.get('version') not in (
                    None, 'val_ndcg_or_ce_divergence_v1'):
                raise ValueError('Unknown legacy early-stopping version; cannot safely migrate')
        model.load_state_dict(checkpoint.pop("model"))
        if not args.eval_only:
            optimizer.load_state_dict(checkpoint.pop("optimizer"))
            if saved_policy is not None:
                scheduler.load_state_dict(checkpoint.pop("scheduler"))
            else:
                old_scheduler = checkpoint.get('scheduler', {})
                if 'step_size' not in old_scheduler or 'gamma' not in old_scheduler:
                    raise ValueError('Unknown legacy scheduler; expected StepLR for policy migration')
                backup = backup_training_policy(args.output_dir)
                migrated_policy = True
                old_lrs = [group['lr'] for group in optimizer.param_groups]
                for group in optimizer.param_groups:
                    group['lr'] = max(float(group['lr']), args.min_lr)
                scheduler._last_lr = [group['lr'] for group in optimizer.param_groups]
                print(f'Migrated StepLR to NDCG plateau; backup={backup}; '
                      f'lr={old_lrs} -> {scheduler.get_last_lr()}. '
                      'Optimizer moments and training cursor retained.', flush=True)
            restore_checkpoint_rng(checkpoint, device, torch)
        epoch = checkpoint["epoch"]
        next_offset = checkpoint["next_offset"]
        global_step = checkpoint["global_step"]
        best_ndcg = best_validation_ndcg(checkpoint)
        if checkpoint.get('selection_metric') == 'ndcg_at_5':
            best_epoch = checkpoint.get('best_epoch')
            best_offset = checkpoint.get('best_offset', 0)
            metric_history = checkpoint.get('metric_history', [])
            training_finished = checkpoint.get('training_finished', False)
        if saved_stopping.get('version') == EARLY_STOPPING_VERSION:
            early_stopping = saved_stopping
        elif not args.eval_only:
            early_stopping['ndcg_anchor'] = best_ndcg if best_ndcg >= 0 else None
            scheduler.best = best_ndcg if best_ndcg >= 0 else float('-inf')
            if saved_stopping.get('version') == 'val_ndcg_or_ce_divergence_v1':
                # Historical CE measurements remain valid, but the old streak
                # counted changes below the new relative threshold as well.
                # Keep terminal states terminal; do not revive a stopped run.
                for key in ('previous_train_ce', 'previous_val_ce',
                            'stopped', 'reason', 'triggered'):
                    early_stopping[key] = saved_stopping[key]
            print('Legacy checkpoint: retaining NDCG best; new NDCG patience starts at zero. '
                  'CE divergence counter resets to zero for the new loss threshold; '
                  'previous CE measurements and terminal stop state are retained. '
                  'Missing historical train losses will not be invented.', flush=True)
        train_epoch_totals = checkpoint.get('train_epoch_totals', train_epoch_totals)
        if not args.eval_only and training_finished and not early_stopping['stopped'] and epoch < args.epochs:
            training_finished = False
            print('Extending completed epoch budget with the retained optimizer and stopping state.', flush=True)
        if checkpoint.get("selection_metric") != "ndcg_at_5":
            needs_metric_baseline = not args.eval_only
            if args.eval_only == 'test':
                raise ValueError('Best checkpoint was selected by another criterion; resume metric-based training first')
            print("Checkpoint selected by an older criterion; optimizer/weights are retained. "
                  "NDCG@5 best tracking will be initialized "
                  "from the resumed model on val.", flush=True)
            early_stopping = new_early_stopping(args.patience, args.loss_patience,
                                                args.min_delta, args.loss_min_delta)
        print(f"Loaded {path}; epoch={epoch}, offset={next_offset:,}", flush=True)
        del checkpoint

    def save(path: Path, save_epoch: int, save_offset: int) -> None:
        atomic_save({
            "model": model.state_dict(), "optimizer": optimizer.state_dict(),
            "scheduler": scheduler.state_dict(), "epoch": save_epoch,
            "next_offset": save_offset, "global_step": global_step,
            "best_ndcg_at_5": best_ndcg, "selection_metric": "ndcg_at_5",
            "best_epoch": best_epoch, "best_offset": best_offset,
            "metric_history": metric_history, "training_finished": training_finished,
            "early_stopping": early_stopping, "train_epoch_totals": train_epoch_totals,
            "training_policy": training_policy,
            "signature": signature,
            "emb_size": args.emb_size, "batch_size": args.batch_size,
            "sample_order": args.sample_order,
            "metadata_projection": args.metadata_projection,
            "model_arguments": model_arguments,
            "cpu_rng": torch.get_rng_state(),
            "cuda_rng": torch.cuda.get_rng_state_all() if device.type == "cuda" else None,
        }, path)

    def write_metric_history() -> None:
        (args.output_dir / 'metric_history.json').write_text(
            json.dumps(metric_history, indent=2), encoding='utf-8')

    if migrated_policy and not needs_metric_baseline:
        save(latest_path, epoch, next_offset)

    print(f"Device={device}; hotels={config['n_node']:,}; fields={len(config['field_names'])}; "
          f"projection={args.metadata_projection}; action_mode={args.action_mode}; "
          f"num_actions={args.num_actions}; event_tokens={args.num_event_tokens}; encoder={args.action_encoder}; "
          f"fusion={args.action_fusion}; metadata_reduction={METADATA_LOSS_REDUCTION}; "
          f"candidate_policy={CANDIDATE_POLICY}; "
          f"patience={args.patience}; loss_patience={args.loss_patience}; "
          f"min_delta={args.min_delta}; loss_min_delta={args.loss_min_delta}; "
          f"scheduler=ReduceLROnPlateau; "
          f"lr_factor={args.lr_factor}; lr_patience={args.lr_patience}; min_lr={args.min_lr}; "
          f"data_schema={config.get('data_schema_version', 2)}; "
          f"action_history_policy={config.get('action_history_policy', 'none')}", flush=True)
    started = time.monotonic()
    if args.eval_only:
        evaluation = make_data(args.prepared_dir, args.eval_only, config, options)
        candidates = load_candidates(args.prepared_dir, args.eval_only)
        metrics = evaluate(model, evaluation, candidates, args.batch_size)
        print(json.dumps({args.eval_only: metrics}, indent=2), flush=True)
        if args.eval_only == 'test':
            write_status(args.output_dir, status="EVALUATED", split=args.eval_only,
                         metrics=metrics, evaluated_checkpoint=str(path), selection_metric='ndcg_at_5',
                         best_epoch=best_epoch, best_val_ndcg_at_5=best_ndcg, training_finished=True,
                         early_stopping=status.get('early_stopping'))
        return

    if training_finished:
        write_metric_history()
        write_status(args.output_dir, status='EARLY_STOPPED' if early_stopping['stopped'] else 'COMPLETE',
                     epochs=epoch, global_step=global_step, early_stopping=early_stopping,
                     best_val_ndcg_at_5=best_ndcg, best_epoch=best_epoch, training_finished=True)
        print('Training already complete; no more updates. Run --eval-only test.', flush=True)
        return

    write_status(args.output_dir, status='RUNNING', epoch=epoch, next_offset=next_offset,
                 global_step=global_step, training_finished=False, early_stopping=early_stopping)
    train = make_data(args.prepared_dir, "train", config, options)
    validation = make_data(args.prepared_dir, "val", config, options)
    val_candidates = load_candidates(args.prepared_dir, "val")
    if not len(train) or not len(validation):
        raise ValueError("Train or val split is empty")
    if needs_metric_baseline:
        print('Validation of resumed checkpoint (not a newly trained epoch)...', flush=True)
        try:
            metrics = evaluate(model, validation, val_candidates, args.batch_size, started, args.max_hours)
        except TimeBudgetExceeded:
            write_status(args.output_dir, status='PAUSED_DURING_VAL_MIGRATION', epoch=epoch,
                         next_offset=next_offset, global_step=global_step)
            return
        best_ndcg = metrics['ndcg_at_5']
        early_stopping['ndcg_anchor'] = best_ndcg
        scheduler.best = best_ndcg
        best_epoch, best_offset = (epoch if next_offset == 0 else epoch + 1), next_offset
        record = {'phase': 'resume_baseline', 'epoch_completed': epoch, 'next_offset': next_offset,
                  'val': metrics}
        metric_history.append(record)
        print(json.dumps(record), flush=True)
        training_finished = epoch >= args.epochs and next_offset == 0
        save(best_path, epoch, next_offset)
        save(latest_path, epoch, next_offset)
        write_metric_history()
    for current_epoch in range(epoch, args.epochs):
        generator = torch.Generator().manual_seed(config["seed"] + current_epoch)
        permutation = torch.randperm(len(train), generator=generator).tolist()
        start_offset = next_offset if current_epoch == epoch else 0
        epoch_lr = optimizer.param_groups[0]['lr']
        model.train()
        print(f"Epoch {current_epoch + 1}/{args.epochs}, "
              f"examples={len(train):,}, start={start_offset:,}, lr={epoch_lr:g}", flush=True)
        for offset in range(start_offset, len(train), args.batch_size):
            indices = permutation[offset:offset + args.batch_size]
            optimizer.zero_grad(set_to_none=True)
            targets, scores, metadata_loss = forward(model, batch_at(train, indices))
            ce_loss = loss_function(scores, targets)
            loss = ce_loss + metadata_loss
            if not torch.isfinite(loss):
                raise FloatingPointError(
                    f"Non-finite objective at epoch {current_epoch + 1}, offset {offset}; "
                    "optimizer step was not applied"
                )
            loss.backward()
            optimizer.step()
            train_epoch_totals['ce_sum'] += float(ce_loss.detach()) * len(indices)
            train_epoch_totals['metadata_sum'] += float(torch.as_tensor(metadata_loss).detach()) * len(indices)
            train_epoch_totals['examples'] += len(indices)
            global_step += 1
            next_offset = min(offset + len(indices), len(train))
            if global_step % 100 == 0:
                print(f"  step={global_step:,}, offset={next_offset:,}/{len(train):,}, "
                      f"elapsed_h={(time.monotonic()-started)/3600:.2f}",
                      flush=True)
            if global_step % args.checkpoint_every == 0:
                save(latest_path, current_epoch, next_offset)
            if args.max_batches and global_step >= args.max_batches:
                save(latest_path, current_epoch, next_offset)
                write_status(args.output_dir, status="SMOKE_STOP", epoch=current_epoch,
                             next_offset=next_offset, global_step=global_step)
                return
            try:
                check_time(started, args.max_hours)
            except TimeBudgetExceeded:
                save(latest_path, current_epoch, next_offset)
                write_status(args.output_dir, status="PAUSED", epoch=current_epoch,
                             next_offset=next_offset, global_step=global_step)
                print("Time budget reached; run again with --resume", flush=True)
                return
        save(latest_path, current_epoch, len(train))
        print("Validation...", flush=True)
        try:
            metrics = evaluate(model, validation, val_candidates, args.batch_size, started,
                               args.max_hours, include_loss=True)
        except TimeBudgetExceeded:
            write_status(args.output_dir, status="PAUSED_DURING_VAL",
                         epoch=current_epoch, global_step=global_step)
            return
        monitored_count = train_epoch_totals['examples']
        train_losses = dict(
            ce_loss=train_epoch_totals['ce_sum'] / monitored_count if monitored_count else None,
            metadata_loss=train_epoch_totals['metadata_sum'] / monitored_count if monitored_count else None,
            total_loss=(train_epoch_totals['ce_sum'] + train_epoch_totals['metadata_sum']) / monitored_count
                       if monitored_count else None,
            examples=monitored_count, complete=monitored_count == len(train),
        )
        improved = metrics["ndcg_at_5"] > best_ndcg
        stopped = update_early_stopping(
            early_stopping, metrics['ndcg_at_5'],
            train_losses['ce_loss'] if train_losses['complete'] else None, metrics['ce_loss'])
        scheduler.step(metrics['ndcg_at_5'])
        next_lr = optimizer.param_groups[0]['lr']
        record = {"epoch": current_epoch + 1, "train": train_losses, "val": metrics,
                  "learning_rate": epoch_lr, "next_learning_rate": next_lr,
                  "lr_reduced": next_lr < epoch_lr,
                  "early_stopping": dict(early_stopping)}
        metric_history.append(record)
        print(json.dumps(record), flush=True)
        if improved:
            best_ndcg = metrics["ndcg_at_5"]
            best_epoch, best_offset = current_epoch + 1, 0
        training_finished = stopped or current_epoch + 1 == args.epochs
        train_epoch_totals = dict(ce_sum=0.0, metadata_sum=0.0, examples=0)
        if improved:
            save(best_path, current_epoch + 1, 0)
        save(latest_path, current_epoch + 1, 0)
        write_metric_history()
        next_offset = 0
        if stopped:
            print(f"Early stopping: {early_stopping['reason']}; best epoch={best_epoch}", flush=True)
            break
    if not best_path.is_file() or best_ndcg < 0:
        raise ValueError('No metric-selected best checkpoint; increase epochs to complete a validation pass')
    write_status(args.output_dir, status="EARLY_STOPPED" if early_stopping['stopped'] else "COMPLETE",
                 epochs=metric_history[-1].get('epoch', epoch) if metric_history else epoch,
                 global_step=global_step, best_val_ndcg_at_5=best_ndcg, best_epoch=best_epoch,
                 selection_metric='ndcg_at_5', training_finished=True, early_stopping=early_stopping)
    print("Training complete; run --eval-only test for local holdout", flush=True)


if __name__ == "__main__":
    main()
